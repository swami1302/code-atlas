    assert check("backend/main.py") == "python"
    assert check("frontend/app/page.tsx") == "tsx"
    assert check("README.md") == "markdown"
    assert check(".github/workflows/ci.yml") == "yaml"
    assert check("Dockerfile.dev") == "dockerfile"
    assert check("frontend/package.json") == "json"
    assert check("frontend/node_modules/react/index.js") is None
    assert check("pnpm-lock.yaml") is None
    assert check("dist/app.min.js") is None
    assert check("big.py", 600_000) is None
    assert check(".env") is None
    assert check("certs/server.pem") is None
    assert check("docs/logo.png") is None
