# The indexing pipeline for one snapshot. worker.py only handles the queue and job
# state; everything about turning a commit into searchable data lives here.

logger = logging.getLogger(__name__)

# Allowlist: only these files are indexed, everything else is skipped. That alone
# keeps out binaries, images, archives, .env files and keys (*.pem, *.key).
# The value is the language tag; chunking uses it to pick a Tree-sitter grammar.
LANGUAGES = {
    # Code: parsed into functions/classes
    ".py": "python",
    ".ts": "typescript",
    ".tsx": "tsx",
    ".js": "javascript",
    ".jsx": "javascript",
    ".mjs": "javascript",
    ".cjs": "javascript",
    ".php": "php",
    # Docs and config: split as plain text
    ".md": "markdown",
    ".mdx": "markdown",
    ".yml": "yaml",
    ".yaml": "yaml",
    ".sql": "sql",
    ".toml": "toml",
}
# Files recognised by their name instead of their extension
NAMED_FILES = {
    "README": "markdown",
    "package.json": "json",
    "composer.json": "json",
    "requirements.txt": "text",
}
# Folders whose .py/.js/.php files are dependencies or build output, not the repo's
# own code (GitHub tarballs never contain .git)
SKIP_DIRS = {
    "node_modules",
    "vendor",
    "venv",
    ".venv",
    "dist",
    "build",
    ".next",
    "out",
    "coverage",
    "target",
}
# Generated by package managers: huge, and full of versions and hashes, not code.
# Other lockfiles (.lock, package-lock.json) already fail the allowlist.
LOCKFILES = {"pnpm-lock.yaml"}
# Real source files are rarely this big; bigger ones are usually generated or data
MAX_FILE_BYTES = 500_000


async def get_snapshot_ref(snapshot_id: UUID) -> tuple[str, str, str]:
    """owner, name and commit_sha of a snapshot. Read from Postgres (the source of
    truth) rather than copied into the BullMQ job, so the two can't disagree."""
    async with SessionLocal() as session:
        row = (
            await session.execute(
                select(Repository.owner, Repository.name, RepoSnapshot.commit_sha)
                .join(RepoSnapshot, RepoSnapshot.repository_id == Repository.id)
                .where(RepoSnapshot.id == snapshot_id)
            )
        ).one()
    return row.owner, row.name, row.commit_sha


def classify(rel: PurePosixPath, size: int) -> str | None:
    """Language tag of a file worth indexing, or None to skip it.
    rel is the path inside the repo, e.g. backend/main.py."""
    name = rel.name
    if SKIP_DIRS.intersection(rel.parts[:-1]) or name in LOCKFILES:
        return None
    # Minified bundles (app.min.js) and oversized files: generated, not written
    if ".min." in name or size > MAX_FILE_BYTES:
        return None
    if name.startswith("Dockerfile"):  # Dockerfile, Dockerfile.dev, ...
        return "dockerfile"
    return NAMED_FILES.get(name) or LANGUAGES.get(rel.suffix.lower())


def read_text(path: Path) -> str | None:
    """The file as text, or None when it isn't really text: a NUL byte or invalid
    UTF-8 means binary data with a code extension. Postgres text columns reject
    NUL, so these files can't be stored as chunks anyway."""
    data = path.read_bytes()
    if b"\x00" in data:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def chunk_files(
    root: Path, files: list[tuple[str, str]]
) -> list[tuple[str, str, chunking.Chunk]]:
    """(path, language, chunk) for every kept file. Blocking disk and CPU work:
    called through asyncio.to_thread."""
    chunks = []
    for rel, language in files:
        text = read_text(root / rel)
        if text is None:
            logger.info("Skipped %s: not UTF-8 text", rel)
            continue
        chunks += [(rel, language, c) for c in chunking.chunk_file(language, text)]
    return chunks


async def save_chunks(
    snapshot_id: UUID, chunks: list[tuple[str, str, chunking.Chunk]]
) -> None:
    """Replace this snapshot's chunk rows in one transaction: all rows land or none.
    Deleting first makes a retry safe after an attempt that crashed halfway."""
    rows = [
        {
            "snapshot_id": snapshot_id,
            "path": path,
            "language": language,
            "start_line": chunk.start_line,
            "end_line": chunk.end_line,
            "symbol": chunk.symbol,
            "kind": chunk.kind,
            "signature": chunk.signature,
            "content": chunk.content,
            "content_hash": content_hash(chunking.embed_text(path, chunk)),
        }
        for path, language, chunk in chunks
    ]
    async with SessionLocal() as session:
        await session.execute(delete(Chunk).where(Chunk.snapshot_id == snapshot_id))
        if rows:  # a bulk insert needs at least one row (a repo of only binaries)
            await session.execute(insert(Chunk), rows)
        await session.commit()


def content_hash(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


async def embed_chunks(
    snapshot_id: UUID, chunks: list[tuple[str, str, chunking.Chunk]]
) -> None:
    """Give every chunk of this snapshot a vector under the current model. Only
    texts without one are sent to the API: unchanged code from an earlier snapshot
    (or another repo) reuses its row. Each batch commits on its own, so a retry
    after a crash resumes where it stopped instead of paying for it all again."""
    texts = {
        content_hash(text): text
        for text in (chunking.embed_text(path, chunk) for path, _, chunk in chunks)
    }
    async with SessionLocal() as session:
        # Hashes of this snapshot with no row yet for this model. Asked in SQL
        # (NOT EXISTS) rather than by sending every hash: one parameter, any size.
        missing = (
            await session.scalars(
                select(Chunk.content_hash)
                .distinct()
                .where(Chunk.snapshot_id == snapshot_id)
                .where(
                    ~exists().where(
                        ChunkEmbedding.content_hash == Chunk.content_hash,
                        ChunkEmbedding.model == embedding.MODEL_KEY,
                    )
                )
            )
        ).all()
        for batch in itertools.batched(missing, embedding.BATCH_SIZE):
            vectors = await embedding.embed_documents([texts[h] for h in batch])
            rows = [
                {"content_hash": h, "model": embedding.MODEL_KEY, "embedding": v}
                for h, v in zip(batch, vectors, strict=True)
            ]
            # DO NOTHING: another job may have stored the same text meanwhile
            await session.execute(
                pg_insert(ChunkEmbedding).on_conflict_do_nothing(), rows
            )
            await session.commit()
    logger.info(
        "Embedded %d new texts, reused %d", len(missing), len(texts) - len(missing)
    )


def unpack(archive: Path, dest: Path) -> Path:
    """Extract the tarball into dest and return the repo root folder.
    Blocking disk work: called through asyncio.to_thread."""
    with tarfile.open(archive) as tar:
        # filter="data" refuses ../ paths, absolute paths, device files and links that
        # point outside dest, so a malicious archive can't write anywhere else
        tar.extractall(dest, filter="data")
    # GitHub archives hold exactly one top-level folder: <owner>-<name>-<sha7>/
    (root,) = dest.iterdir()
    return root


def select_files(root: Path) -> tuple[list[tuple[str, str]], int]:
    """(path inside the repo, language) of every file worth indexing, plus the
    total number of files. Blocking disk work: called through asyncio.to_thread."""
    # ponytail: rglob still walks into skipped folders like node_modules;
    # switch to os.walk with pruning if huge committed dependency folders get slow
    files = [path for path in root.rglob("*") if path.is_file()]
    selected = []
    for path in files:
        rel = path.relative_to(root)  # e.g. backend/main.py
        if language := classify(rel, path.stat().st_size):
            selected.append((str(rel), language))
    return selected, len(files)


async def index_snapshot(snapshot_id: UUID) -> None:
    owner, name, sha = await get_snapshot_ref(snapshot_id)
    logger.info("Indexing %s/%s at %s", owner, name, sha[:7])

    # Everything on disk lives in this folder and is deleted when the block ends,
    # even if indexing fails. Only the results are kept (in Postgres, next steps).
    with tempfile.TemporaryDirectory(prefix="code-atlas-") as tmp:
        archive = Path(tmp) / "repo.tar.gz"
        try:
            size = await download_tarball(owner, name, sha, archive)
        except RepoError as e:
            # Repo gone/private or too large: a retry can't fix it, so tell BullMQ
            # to skip the remaining attempts
            raise UnrecoverableError(str(e)) from e

        # Unpacking is slow, blocking disk work. Running it in a thread keeps the
        # event loop free, so BullMQ can keep renewing its lock on the job.
        root = await asyncio.to_thread(unpack, archive, Path(tmp) / "src")
        files, total = await asyncio.to_thread(select_files, root)
        logger.info(
            "Downloaded %.1f MB, %d files, kept %d: %s",
            size / 1e6,
            total,
            len(files),
            dict(Counter(language for _, language in files)),
        )

        chunks = await asyncio.to_thread(chunk_files, root, files)
        sizes = [len(chunk.content) for _, _, chunk in chunks]
        # max/avg size show whether MAX_CHARS needs tuning
        logger.info(
            "Chunked into %d chunks: %s; max %d chars, avg %d",
            len(chunks),
            dict(Counter(language for _, language, _ in chunks)),
            max(sizes, default=0),
            sum(sizes) // max(len(sizes), 1),
        )

    # Outside the with block: the temp folder is no longer needed
    await save_chunks(snapshot_id, chunks)
    logger.info("Saved %d chunks", len(chunks))
    await embed_chunks(snapshot_id, chunks)


